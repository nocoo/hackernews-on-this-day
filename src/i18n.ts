export type Messages = typeof zh;

export function browserLanguage(languages: readonly string[]): Language {
  const supported = languages.find((language) => /^(zh|en)(-|$)/i.test(language));
  return supported?.toLowerCase().startsWith("zh") ? "zh" : "en";
}
